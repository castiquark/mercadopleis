// Writes src/version.ts from package.json. The version is compiled in rather than read at runtime, because bundlers
// (Next.js on Netlify) move the code away from package.json. Runs before every build; a unit test checks it is current.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const { version } = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8'));
const file = resolve(root, 'src/version.ts');
const content = `// Generated by scripts/gen-version.mjs from package.json. Do not edit.\nexport const VERSION = '${version}';\n`;
let current = '';
try {
  current = readFileSync(file, 'utf8');
} catch {}
if (current !== content) writeFileSync(file, content);
